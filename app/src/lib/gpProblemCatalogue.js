export function findProblemReferenceByName(name) {
  const wanted = String(name || '').trim().toLowerCase()
  if (!wanted) return null
  return GP_PROBLEM_CATALOGUE.find((entry) => entry.name.toLowerCase() === wanted) || null
}

export function searchGPProblems(query, limit = 12) {
  const clean = String(query || '').trim().toLowerCase()
  if (!clean) return []

  const tokens = clean.split(/\s+/).filter(Boolean)
  return GP_PROBLEM_CATALOGUE
    .map((entry) => {
      const name = entry.name.toLowerCase()
      const description = entry.description.toLowerCase()
      let score = 0
      if (name === clean) score += 1000
      if (name.startsWith(clean)) score += 500
      if (name.includes(clean)) score += 250
      for (const token of tokens) {
        if (name.startsWith(token)) score += 120
        else if (name.includes(token)) score += 70
        if (description.includes(token)) score += 15
      }
      return { entry, score }
    })
    .filter((row) => row.score > 0)
    .sort((a, b) => b.score - a.score || a.entry.name.localeCompare(b.entry.name))
    .slice(0, Math.max(1, Number(limit) || 12))
    .map((row) => row.entry)
}

export function problemSignificanceFromReference(reference) {
  return reference?.severity === 'Severe' ? 'Severe' : 'Minor'
}
